const test_palette = "palette K #000000\npalette Y #ffff00\n";
const test_blank_row = "." ** icon_size ++ "\n";
const test_icon_rows = "KK" ++ "." ** 12 ++ "YY\n" ++ test_blank_row ** (icon_size - 1);

test "renderIcons merges a run of one colour into a single rect" {
    const source = test_palette ++ "favicon sun\nicon sun\n" ++ test_icon_rows;
    const icons = try renderIcons(std.testing.allocator, source);
    defer icons.deinit(std.testing.allocator);

    try std.testing.expect(std.mem.find(u8, icons.sprite, "<symbol id=\"sun\" viewBox=\"0 0 16 16\"") != null);
    try std.testing.expect(std.mem.find(u8, icons.sprite, "<rect x=\"0\" y=\"0\" width=\"2\" height=\"1\" fill=\"#000000\"/>") != null);
    try std.testing.expect(std.mem.find(u8, icons.sprite, "<rect x=\"14\" y=\"0\" width=\"2\" height=\"1\" fill=\"#ffff00\"/>") != null);
    try std.testing.expect(std.mem.startsWith(u8, icons.favicon, "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 16 16\""));
    try std.testing.expect(std.mem.find(u8, icons.favicon, "width=\"2\"") != null);
}

test "renderIcons ignores comments and blank lines" {
    const source = "# note\n\n" ++ test_palette ++ "\nfavicon sun\n# another\nicon sun\n" ++ test_icon_rows;
    const icons = try renderIcons(std.testing.allocator, source);
    defer icons.deinit(std.testing.allocator);
    try std.testing.expect(icons.sprite.len > 0);
}

